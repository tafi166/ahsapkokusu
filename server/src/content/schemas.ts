import { z } from 'zod';
import type { BlogPost, Category, FaqItem, Product, Testimonial, TrustSignal } from '@/types';
import contentShapes from './content-shapes.json';

/**
 * Validation for everything the admin panel can write. Editors are trusted with
 * content, not with markup or script: every link must be a site path or https URL
 * (no `javascript:`), every image must be a colour swatch or an uploaded file.
 */

const text = (max: number) => z.string().max(max);
const requiredText = (max: number) => z.string().trim().min(1).max(max);

/** Site-relative path (not protocol-relative `//`) or an https URL. */
export const linkSchema = z
  .string()
  .max(500)
  .refine((v) => /^\/(?!\/)[^\s]*$/.test(v) || /^https:\/\/[^\s"'<>]+$/.test(v), 'Bağlantı "/" ile veya "https://" ile başlamalı.');

export const MEDIA_PATH = /^\/api\/media\/[0-9a-f-]{36}\.(jpg|png|webp)$/;

/** Placeholder colour swatch (seed data) or an image uploaded through /api/admin/media. */
export const imageSrcSchema = z
  .string()
  .max(200)
  .refine((v) => /^#[0-9a-fA-F]{3,8}$/.test(v) || MEDIA_PATH.test(v), 'Görsel bir renk kodu ya da yüklenmiş bir dosya olmalı.');

const swatch = z.string().regex(/^#[0-9a-fA-F]{3,8}$/, 'Renk kodu "#rrggbb" biçiminde olmalı.');
const slug = z.string().max(200).regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, 'Yalnızca küçük harf, rakam ve tire.');
const isoDate = z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Tarih YYYY-AA-GG biçiminde olmalı.');
const stringList = (maxItems: number, maxLen = 200) => z.array(text(maxLen)).max(maxItems);
const money = z
  .number()
  .nonnegative()
  .max(100_000_000)
  .refine((v) => Math.round(v * 100) === v * 100, 'En fazla iki ondalık basamak.');

// ---------------------------------------------------------------------------
// Brand and homepage copy: shape derived from the storefront defaults
// (content-shapes.json, generated by `npm run sync:storefront`)
// ---------------------------------------------------------------------------

/**
 * Builds a strict, all-optional schema from a default object (the storefront
 * merges overrides over defaults, so partial objects are valid). Fields named
 * `*Href` and the social links must be safe links; `hero.images` holds images.
 */
function shapeOf(example: unknown, path: string): z.ZodType {
  if (path === 'hero.images') return z.array(imageSrcSchema).max(12);
  if (path.endsWith('Href') || path.startsWith('social.')) return linkSchema;
  if (typeof example === 'string') return text(5000);
  if (typeof example === 'number') return z.number().finite();
  if (typeof example === 'boolean') return z.boolean();
  if (Array.isArray(example)) return stringList(50, 500);
  if (example && typeof example === 'object') {
    const shape: Record<string, z.ZodType> = {};
    for (const [key, value] of Object.entries(example)) {
      shape[key] = shapeOf(value, path ? `${path}.${key}` : key).optional();
    }
    return z.object(shape).strict();
  }
  throw new Error(`Unsupported default at ${path}`);
}

// ---------------------------------------------------------------------------
// Lists
