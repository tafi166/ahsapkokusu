const id = z.string().min(1).max(64).regex(/^[A-Za-z0-9_-]+$/);

const testimonialSchema: z.ZodType<Testimonial> = z
  .object({
    id,
    authorInitial: requiredText(40),
    rating: z.union([z.literal(1), z.literal(2), z.literal(3), z.literal(4), z.literal(5)]),
    quote: requiredText(1000),
    role: text(100),
  })
  .strict();

const trustSignalSchema: z.ZodType<TrustSignal> = z
  .object({
    id,
    title: requiredText(100),
    description: text(500),
    icon: z.enum(['craft', 'shipping', 'payments', 'reviews']),
  })
  .strict();

const blogPostSchema: z.ZodType<BlogPost> = z
  .object({
    id,
    slug,
    title: requiredText(200),
    excerpt: text(1000),
    date: isoDate,
    readMinutes: z.number().int().min(1).max(600),
    swatch,
  })
  .strict();

const faqItemSchema: z.ZodType<FaqItem> = z.object({ question: requiredText(300), answer: requiredText(3000) }).strict();

/** Editable blocks stored in SiteContent, by key (the storefront's AdminOverrides keys). */
export const contentSchemas = {
  brand: shapeOf(contentShapes.brand, ''),
  homeContent: shapeOf(contentShapes.homeContent, ''),
  announcementMessages: z.array(requiredText(200)).max(10),
  testimonials: z.array(testimonialSchema).max(50),
  trustSignals: z.array(trustSignalSchema).max(12),
  partnerLogos: z.array(requiredText(100)).max(30),
  blogPosts: z.array(blogPostSchema).max(100),
  productFaq: z.array(faqItemSchema).max(50),
} as const;

export type ContentKey = keyof typeof contentSchemas;
export const CONTENT_KEYS = Object.keys(contentSchemas) as ContentKey[];
export const contentKeySchema = z.enum(CONTENT_KEYS as [ContentKey, ...ContentKey[]]);

// ---------------------------------------------------------------------------
// Categories and products
