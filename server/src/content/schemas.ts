const categorySlugSchema = z.enum([
  'parametrik-duvar-tablolari',
  'katmanli-multilayer-tablolar',
  'parametrik-mobilyalar',
  'duvar-saatleri',
  'dekorlar',
]);

export const categorySchema: z.ZodType<Category> = z
  .object({
    slug: categorySlugSchema,
    title: requiredText(100),
    shortDescription: text(500),
    description: text(5000),
    heroSwatch: swatch,
    subcategories: z.array(z.object({ slug, title: requiredText(100) }).strict()).max(30),
    facets: z
      .object({
        price: z.boolean().optional(),
        availability: z.boolean().optional(),
        material: z.boolean().optional(),
        color: z.boolean().optional(),
        subcategory: z.boolean().optional(),
        layerCount: z.boolean().optional(),
      })
      .strict(),
    seoTitle: text(200),
    seoDescription: text(500),
    faq: z.array(faqItemSchema).max(30),
  })
  .strict();

const options = (maxItems = 20) => z.array(requiredText(100)).max(maxItems).optional();
const dimension = z.number().positive().max(100_000).optional();

const variantsSchema = z
  .object({
    sizes: options(),
    widths: options(),
    colors: options(),
    finishes: options(),
    layerCounts: z.array(z.number().int().min(1).max(100)).max(20).optional(),
    frames: options(),
    heightRange: z
      .tuple([z.number().positive(), z.number().positive()])
      .refine(([min, max]) => min < max, 'Yükseklik aralığında en küçük değer en büyükten küçük olmalı.')
      .optional(),
    priceAdjustments: z
      .array(
        z
          .object({
            axis: z.enum(['size', 'width', 'layerCount', 'color', 'finish', 'frame']),
            value: z.union([text(100), z.number()]),
            amount: z.number().finite().min(-100_000_000).max(100_000_000),
          })
          .strict(),
      )
      .max(100)
      .optional(),
  })
  .strict()
  .superRefine((v, ctx) => {
    // A pricing rule must point at an option the product actually offers.
    const offered = {
      size: v.sizes,
      width: v.widths,
      layerCount: v.layerCounts,
      color: v.colors,
      finish: v.finishes,
      frame: v.frames,
    } as Record<string, readonly (string | number)[] | undefined>;
    v.priceAdjustments?.forEach((rule, i) => {
      if (!offered[rule.axis]?.includes(rule.value)) {
        ctx.addIssue({
          code: 'custom',
          path: ['priceAdjustments', i],
          message: `Fiyat kuralı ürünün sunmadığı bir seçeneğe işaret ediyor: ${rule.axis} = ${rule.value}`,
        });
      }
    });
  });

export const productSchema: z.ZodType<Product> = z
  .object({
    id: z.string().regex(/^[a-z0-9-]{1,64}$/, 'Geçersiz ürün kimliği.'),
    slug,
    title: requiredText(200),
    shortTitle: text(100).optional(),
    category: categorySlugSchema,
    subcategory: slug.optional(),
    description: text(5000),
    shortDescription: text(500).optional(),
    price: money,
    compareAtPrice: money.optional(),
    currency: z.enum(['TRY', 'USD']),
    images: z.array(imageSrcSchema).min(1).max(12),
    thumbnail: imageSrcSchema,
    material: text(100).optional(),
    materials: options(),
    dimensions: z
      .object({
        width: dimension,
        height: dimension,
        depth: dimension,
        diameter: dimension,
        thickness: dimension,
        unit: z.enum(['cm', 'in']),
      })
      .strict()
      .optional(),
    weightKg: z.number().positive().max(10_000).optional(),
    colors: options(),
    finishes: options(),
    layerCount: z.number().int().min(1).max(100).optional(),
    productType: z.enum(['wall-art', 'multilayer-art', 'furniture', 'wall-clock', 'decor']),
    productionMethod: z.enum(['CNC Routing', 'Laser Cutting', 'CNC + Hand Finishing']).optional(),
    fileTypes: options(),
    includedFiles: options(),
    softwareCompatibility: options(),
    difficulty: z.enum(['Beginner', 'Intermediate', 'Advanced']).optional(),
    assemblyRequired: z.boolean().optional(),
    assemblyTime: text(100).optional(),
    customizable: z.boolean().optional(),
    personalizationOptions: options(),
    variants: variantsSchema.optional(),
    stock: z.number().int().min(0).max(1_000_000).optional(),
    availability: z.enum(['in-stock', 'made-to-order', 'sold-out', 'digital']),
    deliveryType: z.enum(['DIGITAL', 'PHYSICAL', 'BOTH']),
    featured: z.boolean().optional(),
    bestSeller: z.boolean().optional(),
    newProduct: z.boolean().optional(),
    rating: z.number().min(0).max(5).optional(),
    reviewCount: z.number().int().min(0).max(10_000_000).optional(),
    tags: z.array(text(50)).max(30),
    seoTitle: text(200).optional(),
    seoDescription: text(500).optional(),
    seoKeywords: options(30),
    createdAt: isoDate,
    updatedAt: isoDate,
  })
  .strict()
  .refine((p) => p.compareAtPrice === undefined || p.compareAtPrice > p.price, {
    message: 'Karşılaştırma fiyatı, satış fiyatından yüksek olmalı.',
    path: ['compareAtPrice'],
  });

/** Full replacement list, as the admin panel saves it; ids and slugs must be unique. */
export const productListSchema = z
  .array(productSchema)
  .max(2000)
  .superRefine((list, ctx) => {
    for (const field of ['id', 'slug'] as const) {
      const seen = new Set<string>();
      list.forEach((p, i) => {
        if (seen.has(p[field])) ctx.addIssue({ code: 'custom', path: [i, field], message: `Tekrarlanan ${field}: ${p[field]}` });
        seen.add(p[field]);
      });
    }
  });

export const categoryListSchema = z.array(categorySchema).max(20);
